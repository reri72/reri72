# 중복값 허용 안함
# 각 요소들의 순서를 매길 수 없음
# 중괄호 사용
# 세트 안 요소들은 콤마로 구분

set1 = {1,2,3,4,5}
set2 = set("hello")

print(set1)             # {1, 2, 3, 4, 5}
print(set2)             # {'o', 'e', 'h', 'l'} # 순서 없고 중복값 빼버림

set1 = {}
set2 = set()

print(type(set1))       # <class 'dict'>    # 빈 세트 선언 시 set() 함수 사용해서 선언할 것
print(type(set2))       # <class 'set'>

set1 = {1,2,3,4,5}
set1.add(0)
set1.add(6)
print(set1)             # {0, 1, 2, 3, 4, 5, 6}

set1.update((1,7))
print(set1)             # {0, 1, 2, 3, 4, 5, 6, 7} # 순환 객체 타입만 전당하여 요소 추가

set1.remove(0)
print(set1)             # {1, 2, 3, 4, 5, 6, 7}

# ------------------------------------------------------------------------------------------------------------------------

set1 = {1,2,3,4,5}
set2 = {1,3,5,7,9}

print(set1 | set2)      # {1, 2, 3, 4, 5, 7, 9} # 합집합
print(set1 & set2)      # {1, 3, 5}             # 교집합
print(set1 - set2)      # {2, 4}                # 차집합
print(set1 ^ set2)      # {2, 4, 7, 9}          # 여집합(합집합-교집합)
